"""Traceable QA assets: IDs, models, loader, graph checks, metrics and the ``qa`` CLI.

P0 froze the document model and shipped a loader/CLI that rejects structurally
invalid projects.  P1 added the reference and graph rules (dangling references,
orphans, checklist rules 10-13) and ``qa trace report`` with the four separate
coverage numbers.  P2 added the static ``@pytest.mark.case`` lint (spec rule 9),
the pytest plugin that records run manifests, and the atomic run-history writer.
P3 adds the query and change-propagation layer: content/dependency fingerprints
and the derived index, ``qa trace impact``, ``qa trace stale``, draft batches with
``qa trace review``, and ``qa trace failure``.  The workbench adapter (P4) reads
the same library over HTTP.  P5 adds ``qa trace diff``: the library at a git base
ref is materialised with ``git archive`` (never from the worktree), checked with
the same rules, and compared so CI can fail on a new error, a new dangling
reference or orphan, or a coverage drop.  See ``docs/design/qa-trace.md``.

The pytest plugin lives in :mod:`qa_trace.pytest_plugin` and is deliberately not
imported here: ``pytest`` is a development dependency, and importing the package
must keep working in a plain runtime install.
"""

